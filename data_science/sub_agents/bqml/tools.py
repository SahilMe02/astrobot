def _get_project_id() -> str:
    """
    Return the configured GCP project ID.
    """

    project_id = os.getenv(
        "GOOGLE_CLOUD_PROJECT",
    )

    if not project_id:
        raise RuntimeError(
            "GOOGLE_CLOUD_PROJECT is not configured."
        )

    return project_id


def _get_client() -> bigquery.Client:
    """
    Create a BigQuery client using Application Default Credentials.
    """

    return bigquery.Client(
        project=_get_project_id()
    )


def _get_model_path(
    model_name: str,
) -> str:
    """
    Return fully-qualified escaped BigQuery model path.

    Only approved model names are allowed.
    """

    if model_name not in APPROVED_MODEL_NAMES:
        raise ValueError(
            f"Unsupported model name: {model_name}"
        )

    return (
        f"`{_bqml_dataset()}."
        f"{model_name}`"
    )


def _format_timestamp(
    value: object,
) -> str | None:
    """
    Format API timestamps into ISO-8601 UTC strings.
    """

    if value in (None, ""):
        return None

    if isinstance(
        value,
        datetime,
    ):
        if value.tzinfo is None:
            value = value.replace(
                tzinfo=timezone.utc
            )
        return value.astimezone(
            timezone.utc
        ).isoformat()

    try:
        timestamp_ms = int(value)

        return datetime.fromtimestamp(
            timestamp_ms / 1000,
            tz=timezone.utc,
        ).isoformat()

    except (
        TypeError,
        ValueError,
        OverflowError,
    ):
        return str(value)


def _json_default(
    value: object,
) -> str:
    """
    JSON serializer for BigQuery result values.
    """

    if isinstance(
        value,
        datetime,
    ):
        return value.isoformat()

    if isinstance(
        value,
        date,
    ):
        return value.isoformat()

    if isinstance(
        value,
        time,
    ):
        return value.isoformat()

    if isinstance(
        value,
        Decimal,
    ):
        return str(value)

    return str(value)


def _serialize_rows(
    rows: Any,
) -> list[dict[str, Any]]:
    """
    Convert BigQuery rows into plain dictionaries.
    """

    result: list[dict[str, Any]] = []

    for row in rows:
        if hasattr(
            row,
            "items",
        ):
            result.append(
                dict(row.items())
            )
        else:
            result.append(
                dict(row)
            )

    return result


def _execute_approved_sql(
    sql: str,
    operation: str,
) -> dict[str, Any]:
    """
    Execute SQL generated by an approved internal operation.

    This function is intentionally private.

    The LLM cannot supply arbitrary SQL because the root agent
    does not expose a generic SQL execution tool.
    """

    if not sql or not sql.strip():
        raise ValueError(
            "Approved SQL cannot be empty."
        )

    client = _get_client()

    job = client.query(
        sql,
        location=os.getenv(
            "BQML_LOCATION",
            "US",
        ),
    )

    rows = list(
        job.result()
    )

    return {
        "status": "success",
        "operation": operation,
        "job_id": job.job_id,
        "rows_returned": len(rows),
        "rows": _serialize_rows(rows),
    }


