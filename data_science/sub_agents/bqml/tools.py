def get_model_status(
    model_name: str = REVENUE_MODEL_NAME,
) -> str:
    """
    Return factual metadata for an approved BQML model.
    """

    if model_name not in APPROVED_MODEL_NAMES:
        raise ValueError(
            f"Unsupported model name: {model_name}"
        )

    project_id = _bqml_dataset().split(".")[0]

    model_path = (
        f"{_bqml_dataset()}."
        f"{model_name}"
    )

    client = _get_client()

    try:
        model = client.get_model(
            model_path
        )

    except NotFound:
        return json.dumps(
            {
                "status": "NOT_FOUND",
                "model_path": model_path,
                "project_id": project_id,
                "dataset_id": _bqml_dataset().split(".")[1],
                "model_id": model_name,
                "message": (
                    "The approved BigQuery ML model "
                    "does not exist."
                ),
            },
            ensure_ascii=False,
        )

    except Exception as exc:
        return json.dumps(
            {
                "status": "ERROR",
                "model_path": model_path,
                "project_id": project_id,
                "dataset_id": _bqml_dataset().split(".")[1],
                "model_id": model_name,
                "message": str(exc),
            },
            ensure_ascii=False,
        )

    properties = getattr(
        model,
        "_properties",
        {},
    ) or {}

    model_reference = (
        properties.get(
            "modelReference",
            {},
        )
        or {}
    )

    training_runs = (
        properties.get(
            "trainingRuns",
            [],
        )
        or []
    )

    status: dict[str, Any] = {
        "status": "EXISTS",
        "model_path": model_path,
        "project_id": model_reference.get(
            "projectId",
            project_id,
        ),
        "dataset_id": model_reference.get(
            "datasetId",
            _bqml_dataset().split(".")[1],
        ),
        "model_id": model_reference.get(
            "modelId",
            model_name,
        ),
        "model_type": properties.get(
            "modelType"
        ),
        "location": properties.get(
            "location",
            getattr(
                model,
                "location",
                None,
            ),
        ),
        "creation_time": _format_timestamp(
            properties.get(
                "creationTime"
            )
        ),
        "last_modified_time": _format_timestamp(
            properties.get(
                "lastModifiedTime"
            )
        ),
        "training_run_count": len(
            training_runs
        ),
    }

    if training_runs:
        latest_training_run = (
            training_runs[-1]
        )

        status[
            "latest_training_start_time"
        ] = latest_training_run.get(
            "startTime"
        )

        training_options = (
            latest_training_run.get(
                "trainingOptions"
            )
            or {}
        )

        if training_options:
            status[
                "training_options"
            ] = {
                "model_type": training_options.get(
                    "modelType"
                ),
                "data_frequency": training_options.get(
                    "dataFrequency"
                ),
                "time_series_timestamp_column": (
                    training_options.get(
                        "timeSeriesTimestampColumn"
                    )
                ),
                "time_series_data_column": (
                    training_options.get(
                        "timeSeriesDataColumn"
                    )
                ),
                "horizon": training_options.get(
                    "horizon"
                ),
                "auto_arima": training_options.get(
                    "autoArima"
                ),
            }

    return json.dumps(
        status,
        ensure_ascii=False,
        indent=2,
        default=_json_default,
    )


